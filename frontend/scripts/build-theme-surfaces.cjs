// Maintainer tool: normalize existing CSS colors into semantic dark tokens.
// No layout declarations, chatbot CSS, video CSS or services are rewritten.
const fs=require('node:fs'),path=require('node:path'),postcss=require('postcss');
const directory=path.resolve(__dirname,'../src/styles');
const scope=':root[data-platform-theme="enabled"][data-theme="dark"]:not(:has(.esham-chatbot))';
const excluded=new Set(['esham-chatbot.css','lesson-video-workflow.css','platform-theme.css','theme-surfaces.css']);
const primitive=/--(?:primary|secondary|tertiary|white|black)-/;
const literal=/#(?:[a-f0-9]{3,8})\b|rgba?\([^)]*\)|hsla?\([^)]*\)|(?<![-\w])(?:white|black|red|green|purple|transparent)(?![-\w])/gi;
function family(value,selector){
 const x=value.toLowerCase();
 if(/success|approved|published|active(?!d)|green/.test(selector)&&!/inactive/.test(selector))return 'success';
 if(/error|danger|invalid|rejected|suspended/.test(selector))return 'danger';
 if(/purple|tertiary/.test(selector))return 'purple';
 const hex=x.match(/#([a-f0-9]{6})\b/);if(hex){const [r,g,b]=hex[1].match(/../g).map(v=>parseInt(v,16));if(g>r*1.12&&g>b*1.06)return 'success';if(b>g*1.1&&r>g*1.02)return 'purple';}
 if(/secondary|green/.test(x))return 'success';if(/tertiary|purple/.test(x))return 'purple';
 return null;
}
function token(kind,value,selector){
 const f=family(value,selector);
 if(kind==='color')return /muted|caption|hint|placeholder|description|small/.test(selector)?'var(--muted)':'var(--text)';
 if(kind==='border')return 'var(--border)';
 if(kind==='shadow')return 'color-mix(in srgb, var(--black-00) 35%, transparent)';
 if(f==='success')return 'var(--success-surface)';if(f==='danger')return 'var(--danger-surface)';if(f==='purple')return 'var(--purple-surface)';
 return /hover|selected|active|focus/.test(selector)?'var(--hover-bg)':'var(--surface)';
}
function rewrite(decl,selector){
 const p=decl.prop,v=decl.value;
 if(p.startsWith('--'))return null;
 let kind=p==='color'||p==='fill'||p==='stroke'||p==='-webkit-text-fill-color'?'color':/^(background|accent-color)/.test(p)?'background':/^(border|outline)/.test(p)?'border':/shadow/.test(p)?'shadow':null;
 if(kind==='color'&&/var\(--error-(?:00|300)\)/.test(v))return `${p}: var(--error-200) !important;`;
 if(kind==='color'&&/var\(--(?:primary|admin-accent|green|rose|icon-color|success)\)/.test(v))return `${p}: var(--text) !important;`;
 if(!kind||!/#[a-f0-9]|rgba?\(|hsla?\(|\bwhite\b|\bblack\b|var\(--(?:white|black|primary|secondary|tertiary)-/i.test(v))return null;
 if(p==='fill'||p==='stroke')return null; // Do not recolor artwork or SVG charts.
 if(/url\(/.test(v))return null; // Preserve image assets and illustrations.
 let out=v.replace(/var\(--(?:white|black|primary|secondary|tertiary)-[a-z0-9]+(?:,[^)]*)?\)/gi,m=>token(kind,m,selector));
 out=out.replace(literal,m=>m==='transparent'?m:token(kind,m,selector));
 // Colors inside a fallback resolve to tokens without introducing new literals.
 return out===v?null:`${p}: ${out} !important;`;
}
function scoped(selector){
 return postcss.list.comma(selector).map(s=>{
  s=s.trim();if(s.includes('data-theme')&&s.includes('light'))return null;
  s=s.replace(/(?:html|:root)\[data-theme=['"]dark['"]\]\s*/g,'');
  if(s===':root'||s==='html'||!s)return scope;
  if(s.includes(':root'))return null;
  const exclude=':not(:where(.esham-assistant-launcher,.esham-assistant-launcher *))';
  s=s.includes('::')?s.replace('::',exclude+'::'):s+exclude;
  return `${scope} ${s}`;
 }).filter(Boolean).join(',\n');
}
let output='/* Generated by scripts/build-theme-surfaces.cjs. Color-only overrides; no layout changes. */\n@media screen {\n';let count=0;
for(const file of fs.readdirSync(directory).filter(f=>f.endsWith('.css')&&!excluded.has(f)).sort()){
 const css=postcss.parse(fs.readFileSync(path.join(directory,file),'utf8'));let chunk='';
 css.walkRules(rule=>{
  let parent=rule.parent,at=[],skip=false;while(parent&&parent.type!=='root'){if(parent.type==='atrule'){if(/keyframes|font-face/.test(parent.name)||parent.params==='print')skip=true;else if(['media','supports','container'].includes(parent.name))at.unshift(`@${parent.name} ${parent.params}`);}else skip=true;parent=parent.parent;}
  if(skip||rule.selector.includes('esham-chatbot')||rule.selector.includes('excalidraw'))return;
  const declarations=rule.nodes.filter(n=>n.type==='decl').map(d=>rewrite(d,rule.selector)).filter(Boolean);if(!declarations.length)return;
  const selector=scoped(rule.selector);if(!selector)return;
  let text=selector+' { '+declarations.join(' ')+' }';for(const a of at.reverse())text=a+' { '+text+' }';chunk+=text+'\n';count++;
 });if(chunk)output+='/* '+file+' */\n'+chunk;
}
output+='}\n';fs.writeFileSync(path.join(directory,'theme-surfaces.css'),output);console.log('Generated '+count+' color-only semantic rules.');
