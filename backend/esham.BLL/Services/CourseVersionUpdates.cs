using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using esham.BLL.DTOs;
using esham.BLL.DTOs.Courses;
using esham.BLL.Interfaces;
using esham.DAL.Data;
using esham.DAL.Entities;
using Microsoft.EntityFrameworkCore;
namespace esham.BLL.Services;

public sealed class CourseVersionUpdates(AppDbContext db, INotificationWriter notifications) : ICourseVersionUpdates
{
    public static bool IsEligible(Enrollment enrollment) => enrollment.Status is "active" or "completed";
    public static bool IsCourseCompleted(Enrollment enrollment) => enrollment.Status == "completed" || enrollment.CompletedAt != null;
    public static Guid AccessId(Guid enrollmentId, Guid versionId) => StableId($"esham:version-access:v1:{enrollmentId:D}:{versionId:D}");
    public static Guid UpdateNotificationId(string learnerId, Guid versionId) => StableId($"esham:course-updated:v1:{learnerId}:{versionId:D}");
    private static Guid StableId(string value) => new(SHA256.HashData(Encoding.UTF8.GetBytes(value)).AsSpan(0, 16));
    private void RequireTransaction()
    {
        if (db.Database.CurrentTransaction == null) throw new InvalidOperationException("Version availability requires the business caller's transaction.");
    }
    private async Task<Course?> LockCourse(Guid id, CancellationToken ct) =>
        await (db.Database.IsSqlServer()
            ? db.Courses.FromSqlInterpolated($"SELECT * FROM [Courses] WITH (UPDLOCK, HOLDLOCK) WHERE [Id] = {id}")
            : db.Courses.AsQueryable()).SingleOrDefaultAsync(x => x.Id == id, ct);

    public async Task StageEnrollmentAsync(Enrollment enrollment, CancellationToken ct = default)
    {
        RequireTransaction();
        var course = await LockCourse(enrollment.CourseId, ct);
        if (course == null || course.SafetyStatus != "active" || course.EnrollmentPaused || !IsEligible(enrollment)
            || course.PublishedVersionId != enrollment.CourseVersionId
            || !await db.CourseVersions.AnyAsync(x => x.Id == enrollment.CourseVersionId && x.CourseId == course.Id
                && x.ReviewStatus == "approved" && x.Category.IsActive, ct))
            throw new InvalidOperationException("New enrollment must target the eligible course's current approved publication under the course lock.");
        await StageAccess(enrollment, enrollment.CourseVersionId, null, "enrolled", ct);
    }
    private async Task StageAccess(Enrollment enrollment, Guid versionId, Guid? previousId, string reason, CancellationToken ct)
    {
        var id = AccessId(enrollment.Id, versionId);
        // Also recognizes SQL backfill receipts, whose IDs are generated by SQL.
        if (db.EnrollmentVersionAccess.Local.Any(x => x.EnrollmentId == enrollment.Id && x.CourseVersionId == versionId)
            || await db.EnrollmentVersionAccess.AnyAsync(x => x.EnrollmentId == enrollment.Id && x.CourseVersionId == versionId, ct)) return;
        db.EnrollmentVersionAccess.Add(new() { Id = id, EnrollmentId = enrollment.Id, CourseId = enrollment.CourseId,
            CourseVersionId = versionId, PreviousCourseVersionId = previousId, Reason = reason, WasCourseCompleted = IsCourseCompleted(enrollment) });
    }
    public async Task StagePublicationAsync(Course course, CourseVersion approvedVersion, Guid? previousPublishedVersionId, CancellationToken ct = default)
    {
        RequireTransaction();
        var locked = await LockCourse(course.Id, ct);
        if (!ReferenceEquals(locked, course) || approvedVersion.CourseId != course.Id || course.PublishedVersionId != approvedVersion.Id
            || approvedVersion.ReviewStatus != "approved" || approvedVersion.ApprovedAt == null || course.SafetyStatus != "active")
            throw new InvalidOperationException("Only the locked, successfully approved publication may grant version access.");
        var lessonIdentities = await db.Lessons.Where(x => x.CourseSection.CourseVersionId == approvedVersion.Id).Select(x => x.LogicalLessonId).ToListAsync(ct);
        var taskIdentities = await db.CourseTasks.Where(x => x.CourseVersionId == approvedVersion.Id).Select(x => x.LogicalTaskId).ToListAsync(ct);
        if (lessonIdentities.Contains(Guid.Empty) || taskIdentities.Contains(Guid.Empty)
            || lessonIdentities.Distinct().Count() != lessonIdentities.Count || taskIdentities.Distinct().Count() != taskIdentities.Count)
            throw new InvalidOperationException("Publication requires unambiguous nonempty content lineage.");
        if (previousPublishedVersionId == approvedVersion.Id) return;
        if (previousPublishedVersionId is Guid previous && !await db.CourseVersions.AnyAsync(x => x.Id == previous && x.CourseId == course.Id && x.ReviewStatus == "approved", ct))
            throw new InvalidOperationException("Previous publication must belong to the same course and be approved.");
        var enrollments = await db.Enrollments.Where(x => x.CourseId == course.Id && (x.Status == "active" || x.Status == "completed")).ToListAsync(ct);
        foreach (var enrollment in enrollments)
        {
            await StageAccess(enrollment, enrollment.CourseVersionId, null, "baseline", ct);
            await StageAccess(enrollment, approvedVersion.Id, previousPublishedVersionId, "publication", ct);
            if (previousPublishedVersionId == null) continue;
            var ar = !string.IsNullOrWhiteSpace(approvedVersion.TitleAr) ? approvedVersion.TitleAr : approvedVersion.TitleEn ?? "الدورة";
            var en = !string.IsNullOrWhiteSpace(approvedVersion.TitleEn) ? approvedVersion.TitleEn : approvedVersion.TitleAr ?? "the course";
            await notifications.StageAsync(new(UpdateNotificationId(enrollment.LearnerUserId, approvedVersion.Id), enrollment.LearnerUserId, "course.updated",
                "تحديث الدورة", "Course updated",
                $"تم تحديث دورة {ar}. يمكنك الاطلاع على المحتوى الجديد، مع الاحتفاظ بتقدمك وإنجازاتك السابقة.",
                $"Course {en} has been updated. You can explore the new content while keeping your previous progress and achievements."), ct);
        }
        // Never changes enrollment, progress, submissions, certificates, wallets or point transactions.
        // The business caller saves and commits receipts and notifications with publication.
    }
    private sealed record TaskEvidence(Guid SubmissionId, Guid TaskId, Guid LogicalTaskId, Guid VersionId, DateTimeOffset? EarnedAt);
    private static string LessonContent(Lesson x) => JsonSerializer.Serialize(new {x.TitleAr,x.TitleEn,x.DescriptionAr,x.DescriptionEn,
        x.Objectives,x.ContentType,x.DurationSeconds,x.IsPreview,x.PrimaryVideoMediaAssetId,
        Attachments=x.Attachments.OrderBy(a=>a.SortOrder).ThenBy(a=>a.MediaAssetId).Select(a=>new {a.MediaAssetId,a.DisplayName,a.SortOrder})});
    private static string TaskContent(CourseTask x) => JsonSerializer.Serialize(new {x.TitleAr,x.TitleEn,x.DescriptionAr,x.DescriptionEn,x.Instructions,x.Requirements,
        Attachments=x.Attachments.OrderBy(a=>a.SortOrder).ThenBy(a=>a.MediaAssetId).Select(a=>new {a.MediaAssetId,a.DisplayName,a.SortOrder})});
    public async Task<ServiceResult<EnrollmentVersionState>> GetStateAsync(Guid enrollmentId, string learnerUserId, CancellationToken ct = default)
    {
        var enrollment = await db.Enrollments.AsNoTracking().Include(x => x.Certificate).SingleOrDefaultAsync(x => x.Id == enrollmentId, ct);
        if (enrollment == null) return ServiceResult<EnrollmentVersionState>.Fail(ServiceFailure.NotFound, "Enrollment not found.");
        if (string.IsNullOrWhiteSpace(learnerUserId) || enrollment.LearnerUserId != learnerUserId || !IsEligible(enrollment))
            return ServiceResult<EnrollmentVersionState>.Fail(ServiceFailure.Forbidden, "An eligible enrollment owned by the current learner is required.");
        var course = await db.Courses.AsNoTracking().SingleAsync(x => x.Id == enrollment.CourseId, ct);
        var current = await db.CourseVersions.AsNoTracking().SingleOrDefaultAsync(x => x.Id == course.PublishedVersionId && x.CourseId == course.Id
            && x.ReviewStatus == "approved" && x.Category.IsActive, ct);
        if (course.SafetyStatus != "active" || current == null)
            return ServiceResult<EnrollmentVersionState>.Fail(ServiceFailure.Forbidden, "Approved course content is currently unavailable.");
        var granted = await db.EnrollmentVersionAccess.AsNoTracking().Where(x => x.EnrollmentId == enrollment.Id && x.CourseId == course.Id).Select(x => x.CourseVersionId).ToListAsync(ct);
        if (!granted.Contains(current.Id))
            return ServiceResult<EnrollmentVersionState>.Fail(ServiceFailure.Conflict, "Version availability has not been initialized. Complete the migration/enrollment integration; no local transition is assumed.");
        var originalLessons = await db.Lessons.AsNoTracking().Include(x=>x.Attachments).Where(x => x.CourseSection.CourseVersionId == enrollment.CourseVersionId).ToListAsync(ct);
        var originalTasks = await db.CourseTasks.AsNoTracking().Include(x=>x.Attachments).Where(x => x.CourseVersionId == enrollment.CourseVersionId).ToListAsync(ct);
        var lessons = await db.Lessons.AsNoTracking().Include(x=>x.Attachments).Where(x => x.CourseSection.CourseVersionId == current.Id).OrderBy(x => x.CourseSection.SortOrder).ThenBy(x => x.SortOrder).ThenBy(x => x.Id).ToListAsync(ct);
        var tasks = await db.CourseTasks.AsNoTracking().Include(x=>x.Attachments).Where(x => x.CourseVersionId == current.Id).OrderBy(x => x.SortOrder).ThenBy(x => x.Id).ToListAsync(ct);
        if (lessons.Concat(originalLessons).Any(x => x.LogicalLessonId == Guid.Empty) || tasks.Concat(originalTasks).Any(x => x.LogicalTaskId == Guid.Empty)
            || originalLessons.GroupBy(x => x.LogicalLessonId).Any(x => x.Count() > 1) || lessons.GroupBy(x => x.LogicalLessonId).Any(x => x.Count() > 1)
            || tasks.GroupBy(x => x.LogicalTaskId).Any(x => x.Count() > 1) || originalTasks.GroupBy(x => x.LogicalTaskId).Any(x => x.Count() > 1))
            return ServiceResult<EnrollmentVersionState>.Fail(ServiceFailure.Conflict, "Ambiguous logical identities in the current version require repair; no achievements were transferred.");
        // Existing owned achievements prove their earned version even when pre-migration access history is unknown.
        // Never infer old availability receipts; scope evidence to this course and approved versions.
        var progress = await db.LessonProgressRecords.AsNoTracking().Include(x => x.Lesson).ThenInclude(x => x.CourseSection)
            .Where(x => x.EnrollmentId == enrollment.Id && x.Lesson.CourseSection.CourseVersion.CourseId == course.Id
                && x.Lesson.CourseSection.CourseVersion.ReviewStatus == "approved").ToListAsync(ct);
        // Any immutable approved review earns the logical task forever, regardless of later optional attempts.
        var approvals = await db.TaskSubmissionReviews.AsNoTracking().Include(x => x.TaskSubmission).ThenInclude(x => x.CourseTask)
            .Where(x => x.Decision == "approved" && x.TaskSubmission.EnrollmentId == enrollment.Id
                && x.TaskSubmission.CourseTask.CourseVersion.CourseId == course.Id && x.TaskSubmission.CourseTask.CourseVersion.ReviewStatus == "approved")
            .OrderBy(x => x.ReviewedAt).ThenBy(x => x.Id).ToListAsync(ct);
        // An explicitly persisted legacy approved status is also an achievement;
        // do not infer approval from client-side demo statuses or from a newer optional attempt.
        var legacyApprovals = await db.TaskSubmissions.AsNoTracking().Include(x => x.CourseTask)
            .Where(x => x.EnrollmentId == enrollment.Id && x.Status == "approved"
                && x.CourseTask.CourseVersion.CourseId == course.Id && x.CourseTask.CourseVersion.ReviewStatus == "approved").ToListAsync(ct);
        var evidence = approvals.Select(x => new TaskEvidence(x.TaskSubmission.Id, x.TaskSubmission.CourseTaskId,
            x.TaskSubmission.CourseTask.LogicalTaskId, x.TaskSubmission.CourseTask.CourseVersionId, x.ReviewedAt))
            .Concat(legacyApprovals.Where(x => !approvals.Any(r => r.TaskSubmissionId == x.Id))
                .Select(x => new TaskEvidence(x.Id, x.CourseTaskId, x.CourseTask.LogicalTaskId, x.CourseTask.CourseVersionId, null)))
            .OrderBy(x => x.EarnedAt).ThenBy(x => x.SubmissionId).ToList();
        var completed = IsCourseCompleted(enrollment);
        var lessonStates = lessons.Select(lesson =>
        {
            var original = originalLessons.SingleOrDefault(x => x.LogicalLessonId == lesson.LogicalLessonId);
            var earned = progress.Where(x => x.Lesson.LogicalLessonId == lesson.LogicalLessonId && x.IsCompleted).OrderBy(x => x.LessonId == lesson.Id).ThenBy(x => x.CompletedAt).ThenBy(x => x.Id).FirstOrDefault();
            var own = progress.SingleOrDefault(x => x.LessonId == lesson.Id);
            var prior = progress.Where(x => x.Lesson.LogicalLessonId == lesson.LogicalLessonId && x.LessonId != lesson.Id).OrderByDescending(x => x.UpdatedAt).ThenBy(x => x.Id).FirstOrDefault();
            double? resume = own?.LastPositionSeconds ?? (prior?.Lesson.PrimaryVideoMediaAssetId != null && prior.Lesson.PrimaryVideoMediaAssetId == lesson.PrimaryVideoMediaAssetId ? prior.LastPositionSeconds : null);
            return new LearnerLessonVersionState(lesson.Id, lesson.LogicalLessonId, lesson.CourseSectionId, lesson.TitleAr, lesson.TitleEn,
                original == null, original != null && LessonContent(original) != LessonContent(lesson), earned != null, earned != null && earned.LessonId != lesson.Id,
                completed || earned != null, true, own?.LastPositionSeconds ?? 0, prior?.LastPositionSeconds, resume,
                earned == null ? null : new(earned.Id, earned.LessonId, earned.Lesson.CourseSection.CourseVersionId, earned.CompletedAt));
        }).ToList();
        var taskStates = tasks.Select(task =>
        {
            var original = originalTasks.SingleOrDefault(x => x.LogicalTaskId == task.LogicalTaskId);
            var earned = evidence.FirstOrDefault(x => x.LogicalTaskId == task.LogicalTaskId && x.TaskId != task.Id)
                ?? evidence.FirstOrDefault(x => x.LogicalTaskId == task.LogicalTaskId);
            return new LearnerTaskVersionState(task.Id, task.LogicalTaskId, task.TitleAr, task.TitleEn,
                original == null, original != null && TaskContent(original) != TaskContent(task), earned != null, earned != null && earned.TaskId != task.Id,
                completed || earned != null, completed || earned != null,
                earned == null ? null : new(earned.SubmissionId, earned.TaskId, earned.VersionId, earned.EarnedAt));
        }).ToList();
        var total = lessonStates.Count + taskStates.Count;
        var count = lessonStates.Count(x => x.IsCompleted) + taskStates.Count(x => x.IsApproved);
        var coverage = total == 0 ? 0 : (int)Math.Round(count * 100d / total);
        return ServiceResult<EnrollmentVersionState>.Ok(new(enrollment.Id, course.Id, enrollment.CourseVersionId, current.Id, current.VersionNumber, enrollment.Status,
            completed, enrollment.CompletedAt, enrollment.Certificate?.Id, enrollment.Certificate?.CourseVersionId,
            total, completed ? 0 : total, count, completed ? 100 : coverage, coverage, completed || total > 0 && count == total, false, false, lessonStates, taskStates));
    }
}
